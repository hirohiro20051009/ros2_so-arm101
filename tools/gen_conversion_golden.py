#!/usr/bin/env python3
"""LeRobot 0.4.2 の変換で raw→rad の正解表を作る（開発用。ドライバは lerobot に依存しない）。

実行: ~/miniforge3/envs/ros2_lerobot/bin/python tools/gen_conversion_golden.py

- LeRobot の FeetechMotorsBus を「接続せずに」作り、FeetechMotorsBus._normalize() を直接呼ぶ。
  シリアルは開かない（PortHandler.openPort / setupPort を例外にして保証している）。
- 出典: LeRobot 0.4.2 (Apache-2.0, Copyright 2024 The HuggingFace Inc. team)
    lerobot/motors/motors_bus.py  MotorsBus._normalize()
    lerobot/robots/so101_follower/so101_follower.py  SO101Follower.__init__（モータ定義: DEGREES / RANGE_0_100）
  bridge 側の rad 変換: so_arm101_lerobot_bridge/bridge/bridge.py の math.radians(値)
- 出力 CSV: joint,raw,lerobot_value,rad
    lerobot_value: angle 関節は度、gripper は 0..100
    rad          : math.radians(lerobot_value)（bridge と同じ）
- 対象 raw: 0..4095 の全値 + 範囲外 (-100, 4096, 5000)
"""
import argparse
import json
import math
import os

import scservo_sdk as scs


def _forbid(*_a, **_k):
    raise RuntimeError('このスクリプトはシリアルポートを開かない')


scs.PortHandler.openPort = _forbid
scs.PortHandler.setupPort = _forbid

from lerobot.motors import Motor, MotorCalibration, MotorNormMode  # noqa: E402
from lerobot.motors.feetech import FeetechMotorsBus  # noqa: E402

JOINTS = [
    ('shoulder_pan', 1, MotorNormMode.DEGREES),
    ('shoulder_lift', 2, MotorNormMode.DEGREES),
    ('elbow_flex', 3, MotorNormMode.DEGREES),
    ('wrist_flex', 4, MotorNormMode.DEGREES),
    ('wrist_roll', 5, MotorNormMode.DEGREES),
    ('gripper', 6, MotorNormMode.RANGE_0_100),
]
EXTRA_RAW = [-100, 4096, 5000]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--json', default='~/.cache/huggingface/lerobot/calibration/robots/so101_follower/so101_follower.json')
    ap.add_argument('--out', default='src/so_arm101_hardware/test/data/conversion_golden.csv')
    args = ap.parse_args()

    with open(os.path.expanduser(args.json)) as f:
        cal = json.load(f)
    calibration = {n: MotorCalibration(id=c['id'], drive_mode=c['drive_mode'], homing_offset=c['homing_offset'],
                                       range_min=c['range_min'], range_max=c['range_max']) for n, c in cal.items()}
    bus = FeetechMotorsBus(port='/dev/null-not-opened',
                           motors={n: Motor(i, 'sts3215', m) for n, i, m in JOINTS}, calibration=calibration)
    assert not bus.is_connected

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w') as f:
        f.write('# generated by tools/gen_conversion_golden.py from LeRobot 0.4.2 MotorsBus._normalize (Apache-2.0)\n')
        f.write('joint,raw,lerobot_value,rad\n')
        for name, id_, _ in JOINTS:
            for raw in list(range(4096)) + EXTRA_RAW:
                value = bus._normalize({id_: raw})[id_]
                f.write(f'{name},{raw},{value!r},{math.radians(value)!r}\n')
    print('wrote', args.out)


if __name__ == '__main__':
    main()
